// Builds js/reading-library.js from assets/reading/<id>/index.html.
// Add an article: create a folder assets/reading/<id>/ with index.html and its images, then run `node tools/build-reading.cjs`.
// Articles are listed newest first by date and numbered READING NOTE / 001, 002, ... in that order.
//
// index.html format: a JSON comment at the top, then the article body as HTML.
// Image paths (cover and <img src>) are relative to the article folder; full URLs also work.
//   <!--
//   {
//     "title": "全文標題",
//     "cardTitle": "書架卡片上的短標題",
//     "date": "2026-10-30",
//     "category": "分類 · 分類",
//     "excerpt": "卡片上的一句簡介",
//     "cover": "cover.jpg"
//   }
//   -->
//   <p>內文……</p>
//
// Required: title, cardTitle, date (YYYY-MM-DD), category, excerpt, cover (image file in the article folder).
// Optional: heading   HTML for the article's <h1> (defaults to title), e.g. "人月神話：<br>軟體專案管理之道"
//           bookTitle line under the heading, e.g. "《康乃爾最經典的思考邏輯課》"
//           subtitle  English subtitle line
// Link to another article with: <a href="#reading-<id>" data-detail="reading-<id>">…</a>
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');

const dir = path.join(root, 'assets', 'reading');
const out = path.join(root, 'js', 'reading-library.js');
const required = ['title', 'cardTitle', 'date', 'category', 'excerpt', 'cover'];
const allowed = [...required, 'heading', 'bookTitle', 'subtitle'];
const esc = v => String(v).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

const articles = fs.readdirSync(dir, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort().map(slug => {
  const file = `${slug}/index.html`;
  if (!fs.existsSync(path.join(dir, file))) throw new Error(`${slug}/: missing index.html`);
  // Relative image paths point into the article folder.
  const local = p => /^(https?:|\/|#|data:|assets\/)/.test(p) ? p : `assets/reading/${slug}/${p}`;
  const text = fs.readFileSync(path.join(dir, file), 'utf8').replace(/^﻿/, '');
  const m = text.match(/^\s*<!--([\s\S]*?)-->\s*([\s\S]*)$/);
  if (!m) throw new Error(`${file}: must start with a <!-- { ...JSON... } --> block`);
  let meta;
  try { meta = JSON.parse(m[1]); } catch (e) { throw new Error(`${file}: invalid JSON in the top comment (${e.message})`); }
  const body = m[2].trim().replace(/(<img\b[^>]*?\bsrc=")([^"]+)"/g, (_, before, src) => before + local(src) + '"');
  if (meta.cover) meta.cover = local(meta.cover);
  const problems = [];
  if (!/^[a-z0-9_-]+$/.test(slug)) problems.push('folder name must use a-z, 0-9, _ and -');
  required.filter(k => !meta[k]).forEach(k => problems.push(`"${k}" is required`));
  Object.keys(meta).filter(k => !allowed.includes(k)).forEach(k => problems.push(`unknown field "${k}"`));
  if (meta.date && !/^\d{4}-\d{2}-\d{2}$/.test(meta.date)) problems.push('"date" must be YYYY-MM-DD');
  if (meta.cover && !fs.existsSync(path.join(root, meta.cover))) problems.push(`cover not found: ${meta.cover}`);
  if (!body) problems.push('article body is empty');
  [...body.matchAll(/<img\b[^>]*?\bsrc="([^"]+)"/g)].map(([, src]) => src).filter(src => !/^https?:/.test(src) && !fs.existsSync(path.join(root, src))).forEach(src => problems.push(`image not found: ${src}`));
  if (problems.length) throw new Error(`${file}: ${problems.join('; ')}`);
  return { id: `reading-${slug}`, ...meta, body };
}).sort((a, b) => b.date.localeCompare(a.date) || a.id.localeCompare(b.id));

// Warn about links to articles that don't exist.
const ids = new Set(articles.map(a => a.id));
articles.forEach(a => [...a.body.matchAll(/data-detail="(reading-[^"]+)"/g)].forEach(([, id]) => {
  if (!ids.has(id)) console.warn(`warning: ${a.id} links to missing article ${id}`);
}));

const result = articles.map((a, i) => ({
  id: a.id, title: a.title, cardTitle: a.cardTitle, date: a.date, category: a.category, excerpt: a.excerpt, cover: a.cover,
  html: `<div class="reader-toolbar"><button class="back" data-detail="reading">← 回到閱讀日常</button><span>READING NOTE / ${String(i + 1).padStart(3, '0')}</span></div>`
    + `<div class="article-scroll"><article class="native-article"><div class="eyebrow">${esc(a.category)}</div><h1>${a.heading || esc(a.title)}</h1>`
    + (a.bookTitle ? `<p class="article-book-title">${esc(a.bookTitle)}</p>` : '')
    + (a.subtitle ? `<p class="article-subtitle">${esc(a.subtitle)}</p>` : '')
    + `<div class="native-meta"><time datetime="${a.date}">${a.date.replaceAll('-', '.')}</time></div>`
    + `<div class="article-body">${a.body}</div><div class="article-end"><span>END OF NOTE / 感謝閱讀</span></div></article></div>`
}));

fs.writeFileSync(out, `// Generated by tools/build-reading.cjs from assets/reading/<id>/index.html. Do not edit by hand.\n// Complete articles migrated with the author's authorization.\nconst readingArticles = ${JSON.stringify(result)};\n`);
console.log(`Built ${path.relative(root, out)} with ${articles.length} articles:`);
articles.forEach((a, i) => console.log(`  ${String(i + 1).padStart(3, '0')}  ${a.date}  ${a.cardTitle}`));
