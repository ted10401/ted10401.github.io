// Builds js/portfolio-data.js from assets/portfolio/*.json.
// Add a game: create assets/portfolio/<id>.json, then run `node tools/build-portfolio.cjs`.
//
// Fields:
//   order      number, menu position (ascending)            required
//   title      card title                                   required
//   tag        small label, e.g. "GAME TRAILER"             required
//   youtube    YouTube video id (embedded on detail page)   youtube and/or store required
//   store      Steam (or other) store URL                   youtube and/or store required
//   fullTitle  detail page title, e.g. "罪之門 Guilty Gate"  optional
//   image      poster URL or path like assets/...           optional (defaults to YouTube thumbnail)
//   caption    text under the video                         optional
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');

const dir = path.join(root, 'assets', 'portfolio');
const out = path.join(root, 'js', 'portfolio-data.js');
const allowed = ['order', 'title', 'tag', 'youtube', 'store', 'fullTitle', 'image', 'caption'];

const games = fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort().map(file => {
  const id = path.basename(file, '.json');
  let data;
  try { data = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8').replace(/^﻿/, '')); }
  catch (e) { throw new Error(`${file}: invalid JSON (${e.message})`); }
  const problems = [];
  if (!/^[a-z0-9-]+$/.test(id)) problems.push('file name must use a-z, 0-9 and -');
  if (typeof data.order !== 'number') problems.push('"order" must be a number');
  if (!data.title) problems.push('"title" is required');
  if (!data.tag) problems.push('"tag" is required');
  if (!data.youtube && !data.store) problems.push('needs "youtube" or "store"');
  Object.keys(data).filter(k => !allowed.includes(k)).forEach(k => problems.push(`unknown field "${k}"`));
  if (data.image && !/^https?:/.test(data.image) && !fs.existsSync(path.join(root, data.image))) problems.push(`image not found: ${data.image}`);
  if (problems.length) throw new Error(`${file}: ${problems.join('; ')}`);
  return { id, ...data };
}).sort((a, b) => a.order - b.order);

fs.writeFileSync(out, `// Generated by tools/build-portfolio.cjs from assets/portfolio/*.json. Do not edit by hand.\nconst portfolioGames = ${JSON.stringify(games, null, 2)};\n`);
console.log(`Built ${path.relative(root, out)} with ${games.length} games:`);
games.forEach(g => console.log(`  ${String(g.order).padStart(4)}  ${g.id}  ${g.title}`));
